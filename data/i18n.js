const DICT = { fa, en };

function translator(lang) {
  const d = DICT[lang] || DICT.fa;
  return (key, fallback) => d[key] ?? DICT.fa[key] ?? fallback ?? key;
}

// Persian digits where the locale calls for them; prices/IDs stay isolated (typography.md)
function formatters(lang) {
  const loc = (LOCALES[lang] || LOCALES.fa).digits;
  return {
    num: (n) => Number(n).toLocaleString(loc),
    money: (n) => Number(n) === 0
      ? (lang === 'fa' ? 'رایگان' : 'Free')
      : Number(n).toLocaleString(loc) + (lang === 'fa' ? ' تومان' : ' Toman'),
  };
}

module.exports = { LOCALES, DICT, translator, formatters };
